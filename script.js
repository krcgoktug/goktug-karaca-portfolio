const LANGUAGE_STORAGE_KEY = "portfolio-language";
const THEME_STORAGE_KEY = "portfolio-theme";

const i18nNodes = document.querySelectorAll("[data-i18n]");
const languageButtons = document.querySelectorAll(".language-option");
const themeToggleButton = document.getElementById("themeToggle");
const themeIcon = document.getElementById("themeIcon");
const yearNode = document.getElementById("year");
const htmlNode = document.documentElement;
const bodyNode = document.body;

function applyLanguage(language) {
  const selectedLanguage = translations[language] ? language : "en";
  const dictionary = translations[selectedLanguage];

  i18nNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  document.title = dictionary.page_title;

  const metaDescription = document.querySelector('meta[name="description"]');
  if (metaDescription) {
    metaDescription.setAttribute("content", dictionary.meta_description);
  }

  htmlNode.setAttribute("lang", selectedLanguage);

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === selectedLanguage;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem(LANGUAGE_STORAGE_KEY, selectedLanguage);
}

function applyTheme(theme) {
  const selectedTheme = theme === "light" ? "light" : "dark";

  bodyNode.setAttribute("data-theme", selectedTheme);

  if (themeToggleButton) {
    themeToggleButton.classList.remove("is-dark", "is-light");
    themeToggleButton.classList.add(selectedTheme === "dark" ? "is-dark" : "is-light");
    themeToggleButton.setAttribute("aria-pressed", String(selectedTheme === "dark"));
  }

  if (themeIcon) {
    themeIcon.classList.remove("bi-moon-stars-fill", "bi-sun-fill");
    themeIcon.classList.add(selectedTheme === "dark" ? "bi-moon-stars-fill" : "bi-sun-fill");
  }

  localStorage.setItem(THEME_STORAGE_KEY, selectedTheme);
}

function initializeRevealAnimation() {
  const revealItems = document.querySelectorAll(".reveal");

  const revealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          revealObserver.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.16, rootMargin: "0px 0px -8% 0px" }
  );

  revealItems.forEach((item, index) => {
    item.style.transitionDelay = `${Math.min(index * 35, 320)}ms`;
    revealObserver.observe(item);
  });
}

function initializeNavigationBehavior() {
  const navCollapse = document.getElementById("mainNav");
  if (!navCollapse || !window.bootstrap) {
    return;
  }

  const collapseController = window.bootstrap.Collapse.getOrCreateInstance(navCollapse, {
    toggle: false
  });

  document.querySelectorAll("#mainNav .nav-link").forEach((link) => {
    link.addEventListener("click", () => {
      if (window.innerWidth < 992 && navCollapse.classList.contains("show")) {
        collapseController.hide();
      }
    });
  });
}

if (yearNode) {
  yearNode.textContent = String(new Date().getFullYear());
}

const savedLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY) || "en";
const savedTheme = localStorage.getItem(THEME_STORAGE_KEY) || "dark";

applyLanguage(savedLanguage);
applyTheme(savedTheme);
initializeRevealAnimation();
initializeNavigationBehavior();

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.lang);
  });
});

if (themeToggleButton) {
  themeToggleButton.addEventListener("click", () => {
    const currentTheme = bodyNode.getAttribute("data-theme") === "light" ? "light" : "dark";
    applyTheme(currentTheme === "dark" ? "light" : "dark");
  });
}

